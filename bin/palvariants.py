#!/usr/bin/env python3
"""palvariants.py — Warhol print-run palettes for scene 2.

Reads the 16-color palette from build/art/floppy.i (png2amiga output),
emits build/art/floppypal.i with 8 variants:
  0-3  hue-rotated 0/90/180/270 deg, saturation pushed (silkscreen inks)
  4-7  inverted versions of 0-3 (the 'misprint' flash palettes)
Also writes a preview PNG strip of the floppy in all 8 variants.
"""

import colorsys
import re
import sys

SRC = "build/art/floppy.i"
OUT = "build/art/floppypal.i"


def load_palette(path: str) -> list[tuple[int, int, int]]:
    pal = []
    for line in open(path):
        if line.strip().startswith("dc.w"):
            pal += [int(v.strip().lstrip("$"), 16)
                    for v in line.split("dc.w")[1].split(",")]
    return [((v >> 8) & 15, (v >> 4) & 15, v & 15) for v in pal]


def variant(pal, rot):
    out = []
    for r, g, b in pal:
        h, s, v = colorsys.rgb_to_hsv(r / 15, g / 15, b / 15)
        h = (h + rot / 360.0) % 1.0
        s = min(1.0, s * 1.6 + 0.15)  # silkscreen ink: tint even the paper
        rr, gg, bb = colorsys.hsv_to_rgb(h, s, v)
        out.append((round(rr * 15), round(gg * 15), round(bb * 15)))
    return out


def main() -> None:
    pal = load_palette(SRC)
    variants = [variant(pal, rot) for rot in (0, 90, 180, 270)]
    variants += [[(15 - r, 15 - g, 15 - b) for r, g, b in v]
                 for v in variants[:4]]

    with open(OUT, "w") as f:
        f.write("; generated by palvariants.py — 8 Warhol print-run "
                "palettes, 16 colors each\nfloppy_pals:\n")
        for i, v in enumerate(variants):
            words = ",".join(f"${r:x}{g:x}{b:x}" for r, g, b in v)
            f.write(f"\tdc.w\t{words}\t; variant {i}\n")

    # preview strip
    try:
        from PIL import Image
        data = open("build/art/floppy.bpl", "rb").read()
        w, h, planes, bpr = 160, 128, 4, 20
        idx = [[0] * w for _ in range(h)]
        for y in range(h):
            for p in range(planes):
                base = (y * planes + p) * bpr
                for x in range(w):
                    if data[base + x // 8] >> (7 - (x & 7)) & 1:
                        idx[y][x] |= 1 << p
        strip = Image.new("RGB", (w * 4, h * 2))
        for i, v in enumerate(variants):
            ox, oy = (i % 4) * w, (i // 4) * h
            for y in range(h):
                for x in range(w):
                    r, g, b = v[idx[y][x]]
                    strip.putpixel((ox + x, oy + y),
                                   (r * 17, g * 17, b * 17))
        strip.save("build/art/floppypal_prev.png")
    except ImportError:
        pass
    print(f"{OUT} written ({len(variants)} variants)")


if __name__ == "__main__":
    main()
