#!/usr/bin/env python3
"""makedots.py — scene 3 assets: 16 Ben-Day dot tiles + sine table.

dottab: 16 intensity levels x 16 rows x 1 word — a 16x16 px halftone
dot whose radius grows with intensity (level 15 floods the cell, dots
merge like a Lichtenstein shadow). sintab: 256 bytes, 0..84, so three
summed lookups give 0..252 -> >>4 -> intensity 0..15.
"""

import math

with open("build/art/dottab.i", "w") as f:
    f.write("; 16 dot tiles, 16 words each (generated by makedots.py)\n"
            "dottab:\n")
    for level in range(16):
        r = level * 0.68
        words = []
        for row in range(16):
            w = 0
            for x in range(16):
                if (x - 7.5) ** 2 + (row - 7.5) ** 2 <= r * r:
                    w |= 0x8000 >> x
            words.append(w)
        f.write("\tdc.w\t" + ",".join(f"${w:04x}" for w in words) +
                f"\t; level {level}\n")

with open("build/art/sintab.i", "w") as f:
    f.write("; 256-byte sine table, 0..84 (generated by makedots.py)\n"
            "sintab:\n")
    vals = [round(42 + 42 * math.sin(i * 2 * math.pi / 256))
            for i in range(256)]
    for i in range(0, 256, 16):
        f.write("\tdc.b\t" + ",".join(str(v) for v in vals[i:i + 16]) + "\n")

print("dottab.i, sintab.i written")
