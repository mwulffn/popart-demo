#!/usr/bin/env python3
"""makestamp.py — scene 5 conveyor stamp: 32x32 1-bit floppy icon.

Crisp vector-style 3.5" floppy silhouette (body, shutter, label,
corner notch) as an asm include: 32 rows x 2 dc.w.
"""

from PIL import Image, ImageDraw

img = Image.new("1", (32, 32), 0)
d = ImageDraw.Draw(img)

d.rectangle((1, 1, 30, 30), fill=1)          # body
d.rectangle((26, 1, 30, 4), fill=0)          # corner notch (top right)
d.rectangle((9, 2, 22, 12), fill=0)          # shutter cutout
d.rectangle((11, 4, 15, 10), fill=1)         # shutter window
d.rectangle((6, 17, 25, 29), fill=0)         # label
d.rectangle((8, 20, 23, 21), fill=1)         # label lines
d.rectangle((8, 24, 23, 25), fill=1)
d.rectangle((3, 27, 5, 29), fill=0)          # write-protect hole

px = img.load()
with open("build/art/stamp.i", "w") as f:
    f.write("; 32x32 1-bit floppy stamp (generated by makestamp.py)\n"
            "stamp32:\n")
    for y in range(32):
        w0 = w1 = 0
        for x in range(16):
            if px[x, y]:
                w0 |= 0x8000 >> x
            if px[x + 16, y]:
                w1 |= 0x8000 >> x
        f.write(f"\tdc.w\t${w0:04x},${w1:04x}\n")
img.resize((128, 128)).save("/tmp/stamp-prev.png")
print("stamp.i written")
